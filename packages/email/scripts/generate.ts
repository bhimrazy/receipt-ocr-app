#!/usr/bin/env bun
// Prerenders the React Email sources (src/emails) into src/generated.ts, so production fills
// slots without React or Tailwind.
//
//   bun run email:generate          write src/generated.ts
//   bun run email:check             fail if src/generated.ts is out of date (CI)
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { prerenderAll } from "../src/emails/prerender";

const target = path.join(import.meta.dirname, "../src/generated.ts");
const header = `// Generated by packages/email/scripts/generate.ts from src/emails. Do not edit: change the
// sources and run \`bun run email:generate\`. \`bun run email:check\` (CI) fails when this is stale.
`;
const source = `${header}export const TEMPLATES = ${JSON.stringify(await prerenderAll(), null, 2)} as const;\n`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== source) {
    console.error("email:check: src/generated.ts is out of date. Run `bun run email:generate`.");
    process.exit(1);
  }
  console.log("email:check: generated templates are current");
} else {
  writeFileSync(target, source);
  console.log(
    `email:generate: wrote ${path.relative(process.cwd(), target)} (${source.length} bytes)`,
  );
}
