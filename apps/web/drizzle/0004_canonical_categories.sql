-- Map stored categories onto the canonical list in packages/ai/src/categories.ts
-- (the WHEN pairs must match parseCategory; categories.test.ts checks them).
-- Unrecognised free text becomes 'Other'; blanks become NULL.
UPDATE "receipts" SET "category" = CASE lower(btrim("category"))
  WHEN 'meals' THEN 'Meals'
  WHEN 'groceries' THEN 'Groceries'
  WHEN 'travel' THEN 'Travel'
  WHEN 'fuel' THEN 'Fuel'
  WHEN 'office' THEN 'Office'
  WHEN 'software' THEN 'Software'
  WHEN 'equipment' THEN 'Equipment'
  WHEN 'supplies' THEN 'Supplies'
  WHEN 'utilities' THEN 'Utilities'
  WHEN 'services' THEN 'Services'
  WHEN 'fees' THEN 'Fees'
  WHEN 'other' THEN 'Other'
  WHEN 'grocery' THEN 'Groceries'
  WHEN 'supermarket' THEN 'Groceries'
  WHEN 'food' THEN 'Groceries'
  WHEN 'restaurant' THEN 'Meals'
  WHEN 'restaurants' THEN 'Meals'
  WHEN 'dining' THEN 'Meals'
  WHEN 'meal' THEN 'Meals'
  WHEN 'food & drink' THEN 'Meals'
  WHEN 'coffee' THEN 'Meals'
  WHEN 'cafe' THEN 'Meals'
  WHEN 'gas' THEN 'Fuel'
  WHEN 'petrol' THEN 'Fuel'
  WHEN 'transport' THEN 'Travel'
  WHEN 'transportation' THEN 'Travel'
  WHEN 'taxi' THEN 'Travel'
  WHEN 'lodging' THEN 'Travel'
  WHEN 'hotel' THEN 'Travel'
  WHEN 'office supplies' THEN 'Office'
  WHEN 'stationery' THEN 'Office'
  WHEN 'subscription' THEN 'Software'
  WHEN 'subscriptions' THEN 'Software'
  WHEN 'electronics' THEN 'Equipment'
  WHEN 'hardware' THEN 'Equipment'
  WHEN 'shopping' THEN 'Supplies'
  WHEN 'retail' THEN 'Supplies'
  WHEN 'pharmacy' THEN 'Supplies'
  WHEN 'utility' THEN 'Utilities'
  WHEN 'service' THEN 'Services'
  WHEN 'fee' THEN 'Fees'
  WHEN 'entertainment' THEN 'Other'
  WHEN 'miscellaneous' THEN 'Other'
  ELSE 'Other'
END
WHERE "category" IS NOT NULL AND btrim("category") <> '';--> statement-breakpoint
UPDATE "receipts" SET "category" = NULL WHERE btrim("category") = '';--> statement-breakpoint
-- Uploads that never completed still carry their name in raw_json.
UPDATE "receipts" SET "file_name" = "raw_json"->>'fileName'
WHERE "file_name" IS NULL AND "raw_json" ? 'fileName';
